// Local artifact generation only. Never links, pushes or connects to a database.
import {spawnSync} from 'node:child_process';
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=fileURLToPath(new URL('..',import.meta.url));
const cli=join(root,'tmp/cli-runner/node_modules/@supabase/cli-windows-x64/bin/supabase.exe');
const expected='c221758f3f566d6fa9e0f863c65ad78aebaa4b11d4d9e5bc06f4a7a76ea46aa6';
const frozen=readFileSync(join(root,'database/candidates/release-frozen.sql'));
const hash=buffer=>createHash('sha256').update(buffer).digest('hex');
if(hash(frozen)!==expected)throw new Error('Frozen SQL changed; stop and review');
function run(args){
 const result=spawnSync(cli,args,{cwd:root,encoding:'utf8',timeout:30000});
 if(result.error || result.status!==0){
  process.stderr.write((result.stderr??'').slice(-2500));
  throw result.error??new Error('CLI failed; no database command was requested');
 }
 return result.stdout;
}
const help=run(['migration','--help']);
if(!/\bnew\b/.test(help))throw new Error('Review CLI migration commands');
run(['migration','new','--help']);
const dir=join(root,'supabase/migrations');
function files(){try{return readdirSync(dir);}catch(e){if(e.code==='ENOENT')return [];throw e;}}
const existing=files().filter(name=>name.endsWith('_maat_free_release.sql'));
if(existing.length){
 if(existing.length!==1 || hash(readFileSync(join(dir,existing[0])))!==expected)
  throw new Error('Existing release migration requires review; nothing overwritten');
 console.log('PASS migration already prepared: '+join(dir,existing[0]));
 process.exit(0);
}
const before=new Set(files());
run(['migration','new','maat_free_release']);
const created=files().filter(name=>!before.has(name));
if(created.length!==1 || !/^\d{14}_maat_free_release\.sql$/.test(created[0]))
 throw new Error('Review unexpected CLI output files; none populated');
const target=join(dir,created[0]);
if(readFileSync(target,'utf8').trim())throw new Error('Generated file not empty; not overwritten');
// Populate only the empty file generated by the official CLI.
writeFileSync(target,frozen);
if(hash(readFileSync(target))!==expected)throw new Error('Migration hash mismatch');
console.log('PASS versioned migration: '+target);
console.log('SHA-256: '+expected);
console.log('Local file only; no remote migration applied.');
