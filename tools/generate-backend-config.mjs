import { writeFileSync } from 'node:fs';
import { selectBackend } from './backend-config.mjs';

const config = selectBackend();
writeFileSync(new URL('../src/app/core/config/app-config.generated.ts', import.meta.url),
  `// Generated by tools/generate-backend-config.mjs; public client values only.\nexport const PUBLIC_BACKEND = ${JSON.stringify(config, null, 2)} as const;\n`);
console.log(`Backend configuration: ${config.environment} (${new URL(config.url).hostname})`);
